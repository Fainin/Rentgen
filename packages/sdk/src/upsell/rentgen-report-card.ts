/**
 * <rentgen-report-card> (Stream 5) — a shareable summary of the latest scan: item count,
 * idle total, top-3 items by rent/day, monthly projection. Extensible via named light-DOM
 * slots (header, badges, cta, footer) so any host can override a region without touching
 * this file — unslotted regions fall back to Rentgen's own default content.
 */

import { css, html, LitElement, nothing } from 'lit';
import type { ScanResult } from '../types.js';
import { on } from '../events.js';
import { formatMoney } from './format.js';
import { midpoint, monthlyProjection, rankByRentPerDay } from './projection.js';

const TOP_ITEM_COUNT = 3;

export class RentgenReportCard extends LitElement {
  static styles = css`
    :host {
      display: block;
      font-family: var(--rentgen-font, system-ui, sans-serif);
      color: #e5e7eb;
    }
    .card {
      background: var(--rentgen-card-bg, #16181d);
      border-radius: var(--rentgen-radius, 20px);
      padding: 1.25rem;
      border: 1px solid #262a32;
    }
    .title {
      margin: 0 0 0.5rem;
      font-size: 1.1rem;
      font-weight: 800;
      color: #fff;
    }
    .badges {
      display: flex;
      gap: 0.5rem;
      margin-bottom: 0.85rem;
    }
    .badge {
      border: 1px solid #3a4150;
      border-radius: 999px;
      padding: 0.15rem 0.7rem;
      font-size: 0.8rem;
      color: #b7c0ba;
    }
    .badge.accent {
      color: var(--rentgen-accent, #86efac);
      border-color: var(--rentgen-accent, #86efac);
      background: rgba(134, 239, 172, 0.12);
    }
    .top-items {
      list-style: none;
      margin: 0 0 0.75rem;
      padding: 0;
    }
    .top-items li {
      display: flex;
      justify-content: space-between;
      padding: 0.3rem 0;
      border-bottom: 1px solid #262a32;
      font-size: 0.9rem;
    }
    .top-items li:last-child {
      border-bottom: none;
    }
    .top-items .rent {
      color: var(--rentgen-accent, #86efac);
      font-weight: 700;
    }
    .projection {
      color: #9ca3af;
      font-size: 0.85rem;
      margin-bottom: 0.5rem;
    }
    .footer {
      color: #6b7280;
      font-size: 0.75rem;
      margin-top: 0.5rem;
    }
  `;

  declare private result: ScanResult | null;

  static get properties() {
    return { result: { state: true } };
  }

  private unsubscribe: (() => void) | null = null;

  constructor() {
    super();
    this.result = null;
  }

  connectedCallback(): void {
    super.connectedCallback();
    this.unsubscribe = on('scan:complete', (result) => {
      this.result = result;
    });
  }

  disconnectedCallback(): void {
    super.disconnectedCallback();
    this.unsubscribe?.();
    this.unsubscribe = null;
  }

  render() {
    const result = this.result;
    if (!result) return nothing;
    const top = rankByRentPerDay(result.items).slice(0, TOP_ITEM_COUNT);
    const monthly = monthlyProjection(result.items);

    return html`
      <div class="card">
        <slot name="header">
          <h3 class="title">Your idle capital report</h3>
        </slot>
        <slot name="badges">
          <div class="badges">
            <span class="badge">${result.items.length} items</span>
            <span class="badge accent"
              >${formatMoney(result.totalIdleValue, result.currency)} idle</span
            >
          </div>
        </slot>
        <ul class="top-items">
          ${top.map(
            (item) => html`
              <li>
                <span>${item.name}</span>
                <span class="rent"
                  >${formatMoney(midpoint(item.rentPerDay), item.rentPerDay.currency)}/day</span
                >
              </li>
            `,
          )}
        </ul>
        <div class="projection">
          ~${formatMoney(monthly, result.currency)}/month if rented out
        </div>
        <slot name="cta"></slot>
        <slot name="footer">
          <div class="footer">Generated by Rentgen</div>
        </slot>
      </div>
    `;
  }
}

if (!customElements.get('rentgen-report-card')) {
  customElements.define('rentgen-report-card', RentgenReportCard);
}
